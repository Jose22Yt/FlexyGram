    private static void own(String key,String source,String route){owners.put(key,new String[]{source,route});}
    private static String key(AbstractConfigCell cell){return cell instanceof WithKey?((WithKey)cell).getKey():null;}
    public static boolean accepts(AbstractConfigCell cell,String source,String route){
        String key=key(cell);if(key==null)return true;if(owned.contains(key))return false;
        String[] owner=owners.get(key);
        if(owner==null)return route.equals(source.equals("ng")?"general_extra":source.equals("nc")?"messages_extra":"advanced_extra");
        return owner[0].equals(source)&&owner[1].equals(route);
    }
    public static Set<String> sources(String route){Set<String> result=new LinkedHashSet<>();for(String[] value:owners.values())if(route.equals(value[1]))result.add(value[0]);return result;}
    public static String routeForKey(String key){String[] owner=owners.get(key);return owner==null?"general_extra":owner[1];}
    public static BaseFragment forKey(String key){String[] owner=owners.get(key);return owner==null?null:screen(owner[0],owner[1]);}
    public static BaseFragment open(String route){
        Set<String> sources=sources(route);if(sources.size()==1)return screen(sources.iterator().next(),route);
        return new SignatureSettingsActivity(route);
    }
    public static BaseFragment screen(String source,String route){
        BaseNekoXSettingsActivity f;
        switch(source){case "ng":f=new NekoGeneralSettingsActivity();break;case "nc":f=new NekoChatSettingsActivity();break;case "nx":f=new NekoExperimentalSettingsActivity();break;default:throw new IllegalArgumentException("Unknown legacy source");}
        f.useSignatureSettingsPage(source,route,SignatureSettingsRegistry.entry(route).title);return f;
    }

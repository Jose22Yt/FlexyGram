"""Explicit P0.4b review boundary layered on immutable P0.3g snapshots.
Hashes are never generated by tests. A changed file outside this boundary fails.
"""
from pathlib import Path
import hashlib,json,subprocess
ROOT=Path(__file__).resolve().parents[2]
import sys
sys.path.insert(0,str(ROOT/'tests/native_compatibility'))
from scope_native import reviewed_native_change, assert_native_scope
BASE='d9f2b788cf23e830e84ba24e9f6cb2e71e13bd4d'
def reviewed_variant_change(path,previous=None):
 if reviewed_native_change(path,previous):return True
 rows=json.loads(Path(__file__).with_name('reviewed_changes.json').read_text())['files']
 if path not in rows:return False
 row=rows[path];current=ROOT/path
 before=subprocess.run(['git','show',BASE+':'+path],cwd=ROOT,capture_output=True)
 old=hashlib.sha256(before.stdout).hexdigest() if before.returncode==0 else None
 return current.is_file() and hashlib.sha256(current.read_bytes()).hexdigest()==row['after'] and old==row['before'] and (previous is None or previous in row['previous'])
def assert_variant_scope(test):
 assert_native_scope(test)
 changed=subprocess.check_output(['git','diff','--name-only','--ignore-submodules',BASE],cwd=ROOT,text=True).splitlines()
 for path in changed:
  if path.startswith(('docs/security-p04b/','tests/build_variants/','docs/security-p04c/','tests/native_compatibility/')):continue
  test.assertTrue(reviewed_variant_change(path),path)
